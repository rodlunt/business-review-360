/**
 * Helper to check if we're on an org-based URL
 * @param {Page} page - Playwright page object
 * @param {string} expectedPath - Expected path after org ID (e.g., 'review', 'submit')
 * @param {string} organizationId - Organization ID (defaults to TEST_ORG_ID)
 */
export async function expectOrgUrl(page, expectedPath, organizationId = TEST_ORG_ID) {
  const currentUrl = page.url();
  const expectedUrl = `/org/${organizationId}/${expectedPath}`;
  if (!currentUrl.includes(expectedUrl)) {
    throw new Error(`Expected URL to contain ${expectedUrl}, but got ${currentUrl}`);
  }
}

/**
 * Dismiss a Shepherd.js tour dialog if one is currently blocking the UI.
 *
 * auth.jsx clears localStorage before the login POST, so initScript-seeded
 * tour-seen keys are gone by the time user state is set and the tour fires.
 * Call this before any admin interaction that could be blocked by the overlay.
 *
 * @param {Page} page - Playwright page object
 */
// NOTE: the 3s timeout is intentional. auth.jsx calls localStorage.clear() before
// the login POST, so shepherd_tour_seen_* keys are always absent and the tour
// always fires. If that upstream behaviour changes, these 3s become dead weight.
export async function dismissTourIfOpen(page) {
  try {
    await page.locator('.shepherd-modal-overlay-container.shepherd-modal-is-visible')
      .waitFor({ state: 'visible', timeout: 3000 });
    // AdminTour uses "Skip tour"; UserTour uses "Skip" — /skip/i matches both.
    // Fall back to the cancel icon (x) if the tour has advanced past step 1
    // and the Skip button is no longer rendered.
    const skipBtn = page.getByRole('button', { name: /skip/i }).first();
    const cancelIcon = page.locator('.shepherd-cancel-icon').first();
    const skipVisible = await skipBtn.isVisible().catch(() => false);
    if (skipVisible) {
      await skipBtn.click();
    } else {
      await cancelIcon.waitFor({ state: 'visible', timeout: 2000 });
      await cancelIcon.click();
    }
    await page.locator('.shepherd-modal-overlay-container')
      .waitFor({ state: 'hidden', timeout: 5000 });
  } catch {
    // No tour appeared within the timeout — nothing to dismiss
  }
}

/**
 * Helper function to navigate to admin settings via the admin dropdown menu
 * @param {Page} page - Playwright page object
 */
export async function navigateToAdminSettings(page) {
  await dismissTourIfOpen(page);
  await page.click('[data-testid="admin-menu-button"]');
  await page.waitForTimeout(300);
  await page.click('[data-testid="admin-settings-menu-item"]');
  await page.waitForLoadState('load');
}

