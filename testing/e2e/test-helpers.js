/**
 * Test Helper Utilities for Organization-Based Routing
 *
 * This file provides helper functions for Playwright tests to work with
 * the organization-based routing structure (/org/{organizationId}/...).
 *
 * Default test organization: demo-corp
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Default test organization ID used across all tests
 */
export const TEST_ORG_ID = 'demo-corp';

/**
 * Issue #544: reset-database is gated by a per-boot bearer token generated by
 * the backend and written to backend/.test-reset-token. Tests must read that
 * file and pass the value as the X-Test-Reset-Token header. Playwright and
 * the backend run on the same host, so file-system handoff is sufficient.
 */
const TEST_RESET_TOKEN_PATH = path.resolve(
  __dirname,
  '../../backend/.test-reset-token'
);

let cachedResetToken = null;

function readTestResetToken() {
  if (cachedResetToken) return cachedResetToken;
  try {
    cachedResetToken = fs.readFileSync(TEST_RESET_TOKEN_PATH, 'utf8').trim();
  } catch (err) {
    throw new Error(
      `Unable to read test reset token at ${TEST_RESET_TOKEN_PATH}. ` +
      `Start the backend with ALLOW_DESTRUCTIVE_TEST_ENDPOINTS=true so the ` +
      `token file is generated before the Playwright run.`
    );
  }
  return cachedResetToken;
}

export async function resetTestDatabase(request) {
  const token = readTestResetToken();
  const response = await request.post(
    'http://localhost:4000/api/setup/reset-database',
    {
      headers: { 'X-Test-Reset-Token': token },
      data: {},
    }
  );
  if (!response.ok()) {
    throw new Error(
      `reset-database returned ${response.status()}: ${await response.text()}`
    );
  }
  return response;
}

/**
 * Helper function to navigate to organization login page
 * @param {Page} page - Playwright page object
 * @param {string} organizationId - Organization ID (defaults to TEST_ORG_ID)
 */
export async function gotoLogin(page, organizationId = TEST_ORG_ID) {
  // Inject localStorage BEFORE the page loads so LoginForm's useEffect fires
  // with the correct orgId. Without this the settings fetch runs at mount time
  // with an empty localStorage (orgId not yet set) and defaults useCaptcha=true,
  // causing reCAPTCHA to run in headless Chrome and returning 401.
  await page.addInitScript((id) => {
    localStorage.setItem('organizationId', id);
    // Suppress onboarding tours for all known test user IDs so Shepherd overlays
    // never intercept UI interactions in E2E tests.
    ['44444444-4444-4444-4444-444444444444',
     '66666666-6666-6666-6666-666666666666',
     '55555555-5555-5555-5555-555555555555',
     '88888888-8888-8888-8888-888888888888',
     '99999999-9999-9999-9999-999999999999'].forEach(userId => {
      ['superuser', 'admin', 'user'].forEach(type => {
        localStorage.setItem(`shepherd_tour_seen_${userId}_${type}`, '1');
      });
    });
  }, organizationId);

  await page.goto(`/org/${organizationId}/login`);

  // On production, App.jsx redirects /org/:id/login → <id>.br360.example.com/login
  // via window.location.href after React mounts. page.goto may return before that
  // JS-triggered redirect fires, leaving us on the apex. If so, wait for the redirect
  // to complete so the form fill and API call happen on the correct subdomain (not
  // the apex, where the in-flight fetch would be cancelled when the redirect fires
  // mid-request).
  const afterGotoHostname = new URL(page.url()).hostname;
  if (afterGotoHostname === 'br360.example.com') {
    // The apex serves the Hugo marketing site — the React SPA lives on tenant subdomains.
    // Navigate directly; a JS redirect will never fire on the apex.
    await page.goto(`https://${organizationId}.br360.example.com/org/${organizationId}/login`);
    await page.waitForLoadState('load');
  }

  // #892: the org-scoped login credential field is email, not username.
  await page.locator('[data-testid="email"]').first().waitFor({ state: 'visible', timeout: 45000 });
}

