/**
 * Helper function to build org-based URL
 * @param {string} path - Path after org ID (e.g., '/review', '/submit')
 * @param {string} organizationId - Organization ID (defaults to TEST_ORG_ID)
 * @returns {string} Full URL with org prefix
 */
export function orgUrl(path, organizationId = TEST_ORG_ID) {
  const cleanPath = path.startsWith('/') ? path.slice(1) : path;
  return `/org/${organizationId}/${cleanPath}`;
}

/**
 * Helper function to login as a user
 * @param {Page} page - Playwright page object
 * @param {string} email - Email (the sole login credential since #892)
 * @param {string} password - Password
 * @param {string} organizationId - Organization ID (defaults to TEST_ORG_ID)
 */
export async function loginUser(page, email, password, organizationId = TEST_ORG_ID) {
  await gotoLogin(page, organizationId);

  const emailInput = page.locator('[data-testid="email"] input').first();
  await emailInput.waitFor({ state: 'visible', timeout: 15000 });
  await emailInput.fill(email);
  await page.locator('[data-testid="password"] input').first().fill(password);
  await page.locator('[data-testid="submit-button"]').first().click();

  // Accept the org-prefixed path (/org/:id/review) OR the bare subdomain path
  // (/review) — production redirects /org/:id/login to the tenant subdomain.
  await page.waitForURL(
    (url) =>
      url.href.includes(`/org/${organizationId}/review`) ||
      /\/review$/.test(url.pathname),
    { timeout: 30000 }
  );
}

/**
 * Helper function to register a new user
 * @param {Page} page - Playwright page object
 * @param {string} email - Email (the sole credential, #892 register slice)
 * @param {string} password - Password
 * @param {string} organizationId - Organization ID (defaults to TEST_ORG_ID)
 */
export async function registerUser(page, email, password, organizationId = TEST_ORG_ID) {
  await gotoLogin(page, organizationId);
  await page.waitForTimeout(1000);

  const registerButton = page.getByText('NEED AN ACCOUNT? REGISTER');
  await registerButton.click();
  await page.waitForTimeout(1000);

  // #892 register slice: RegisterForm's username field is gone entirely --
  // the "username" testid no longer exists anywhere on the page. Email,
  // password, confirmPassword and submit-button keep the same indices as
  // before (LoginForm's own fields at [0], RegisterForm's at [1] where
  // shared; confirmPassword is RegisterForm-only, so first()) since none
  // of those testid counts were affected by removing username.
  await page.locator('[data-testid="email"] input').nth(1).fill(email);
  await page.locator('[data-testid="password"] input').nth(1).fill(password);
  await page.locator('[data-testid="confirmPassword"] input').first().fill(password);
  await page.locator('[data-testid="submit-button"]').nth(1).click();

  await page.waitForURL(
    (url) =>
      url.href.includes(`/org/${organizationId}/review`) ||
      /\/review$/.test(url.pathname),
    { timeout: 15000 }
  );
}

